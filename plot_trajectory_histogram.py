fig, ax = plt.subplots(figsize=(14, 7))

# Use log scale for x-axis to handle the wide range
# Create bins in log space
bins = np.logspace(np.log10(500), np.log10(250000), 50)

# Create weights to normalize each histogram to show fraction (sums to 1)
